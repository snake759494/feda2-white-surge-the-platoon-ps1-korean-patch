def render(text, w, h, bold):
    S = 4
    font = FONT_B if bold else FONT
    for size in range(min(h + 3, 20), 7, -1):
        f = ImageFont.truetype(font, size * S)
        bb = f.getbbox(text)
        tw = (bb[2] - bb[0]) / S
        th = (bb[3] - bb[1]) / S
        if tw <= w - 2 and th <= h:
            break
    im = Image.new('L', (w * S, h * S), 0)
    oy = (h * S - (bb[3] - bb[1])) // 2 - bb[1]
    ImageDraw.Draw(im).text((S - bb[0], oy), text, font=f, fill=255)
    im = im.resize((w, h), Image.LANCZOS)
    g = np.array(im).astype(np.int32)
    return np.clip((g * 15 + 127) // 255, 0, 15).astype(np.uint8)


def page(kd, off, items):
    r = np.frombuffer(bytes(kd[off:off + 0x8000]), np.uint8).reshape(256, 128)
    a = np.empty((256, 256), np.uint8); a[:, 0::2] = r & 15; a[:, 1::2] = r >> 4
    for y0, y1, x0, x1, t in items:
        a[y0:y1, x0:x1] = 0
    for y0, y1, x0, x1, t in items:
        bold = t.startswith('#')
        g = render(t.lstrip('#'), x1 - x0, y1 - y0, bold)
        reg = a[y0:y1, x0:x1]
        np.maximum(reg, g, out=reg)
    kd[off:off + 0x8000] = ((a[:, 0::2] & 15) | (a[:, 1::2] << 4)).astype(np.uint8).tobytes()
    return a


def patch(kd):
    return page(kd, PA, ITEMS_A), page(kd, PB, ITEMS_B), page(kd, PC, ITEMS_C)


